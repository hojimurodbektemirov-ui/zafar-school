"""Build public/index.html (Uzbek, improved Latin alphabet), public/ru.html and public/en.html
from site/index.src.html + site/i18n.json, and public/js/t.<lang>.js from site/strings.py.
Usage:  python3 site/build_i18n.py        (fails if any translation is missing)
"""
import json, os, re, sys
from bs4 import BeautifulSoup, NavigableString, Comment, Tag
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from i18n_core import units, skip_el, to_new_alphabet, ATTRS, norm
import strings

ROOT = os.path.dirname(HERE)
PUB = os.path.join(ROOT, 'public')
SRC = open(os.path.join(HERE, 'index.src.html'), encoding='utf-8').read()
I18N_PATH = os.path.join(HERE, 'i18n.json')
PAGES = {'uz': 'index.html', 'ru': 'ru.html', 'en': 'en.html'}
LOCALE = {'uz': 'uz_UZ', 'ru': 'ru_RU', 'en': 'en_US'}
TAGS = re.compile(r'<\s*(/?)\s*([a-zA-Z0-9]+)')

def seed():
    """First run: build i18n.json from the unit order (todo.json) and tr_data.TR."""
    from tr_data import TR
    keys = json.load(open(os.path.join(HERE, 'todo.json'), encoding='utf-8'))
    assert len(keys) == len(TR), f'{len(keys)} units vs {len(TR)} translations'
    out = {}
    for k, (ru, en) in zip(keys, TR):
        out[k] = {'ru': k if ru == '=' else ru, 'en': k if en == '=' else en}
    json.dump(out, open(I18N_PATH, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)

def check_tags(src, dst, lang):
    a = [m.groups() for m in TAGS.finditer(src)]
    b = [m.groups() for m in TAGS.finditer(dst)]
    if a != b:
        raise SystemExit(f'[{lang}] markup mismatch:\n  src: {src[:120]}\n  dst: {dst[:120]}')

def frag(html):
    return BeautifulSoup(html, 'html.parser')

def translate(lang, tr):
    soup = BeautifulSoup(SRC, 'html.parser')
    if lang == 'uz':
        for node in list(soup.find_all(string=True)):
            if isinstance(node, Comment) or skip_el(node.parent):
                continue
            new = to_new_alphabet(str(node))
            if new != str(node):
                node.replace_with(NavigableString(new))
        for el in soup.find_all(True):
            if skip_el(el):
                continue
            for a in ATTRS:
                if el.has_attr(a):
                    el[a] = to_new_alphabet(el[a])
        for m in soup.find_all('meta'):
            if m.get('name') == 'description' or m.get('property') in ('og:title', 'og:description'):
                m['content'] = to_new_alphabet(m['content'])
    else:
        missing = []
        for kind, node, key in list(units(soup)):
            t = tr.get(key, {}).get(lang)
            if t is None:
                missing.append(key); continue
            if kind == 'el':
                check_tags(key, t, lang)
                node.clear()
                for ch in list(frag(t).contents):
                    node.append(ch)
            elif kind == 'txt':
                raw = str(node)
                lead, trail = raw[:len(raw) - len(raw.lstrip())], raw[len(raw.rstrip()):]
                node.replace_with(NavigableString(lead + t + trail))
            else:
                el, a = node
                el[a] = t
        if missing:
            raise SystemExit(f'[{lang}] {len(missing)} missing translations, run site/extract.py. First: {missing[0][:100]}')

    # page-level language wiring
    soup.html['lang'] = lang
    head = soup.head
    for code, page in PAGES.items():
        link = soup.new_tag('link', rel='alternate', hreflang=code, href=page)
        head.append(link)
    head.append(soup.new_tag('meta', property='og:locale', content=LOCALE[lang]))
    for a in soup.select('#lang a'):
        if a.get('hreflang') == lang:
            a['aria-current'] = 'page'
    site_js = soup.find('script', src='js/site.js')
    site_js.insert_before(soup.new_tag('script', src=f'js/t.{lang}.js?v={ver(f"t.{lang}.js")}', defer=None))
    site_js.insert_before('\n')
    site_js['src'] = f'js/site.js?v={ver("site.js")}'
    return str(soup)

def ver(name):
    # short content hash so browsers fetch the new file after every change
    import hashlib
    return hashlib.md5(open(os.path.join(PUB, 'js', name), 'rb').read()).hexdigest()[:8]

def build_strings():
    for lang in PAGES:
        data = strings.for_lang(lang)
        if lang == 'uz':
            data = translit_values(data)
        js = '/* generated by site/build_i18n.py */\nwindow.ZIS_T=' + json.dumps(data, ensure_ascii=False) + ';\n'
        open(os.path.join(PUB, 'js', f't.{lang}.js'), 'w', encoding='utf-8').write(js)

def translit_values(v):
    # transliterate string values only; dict keys stay as they are
    if isinstance(v, str):
        return to_new_alphabet(v)
    if isinstance(v, list):
        return [translit_values(x) for x in v]
    if isinstance(v, dict):
        return {k: translit_values(x) for k, x in v.items()}
    return v

if __name__ == '__main__':
    if not os.path.exists(I18N_PATH):
        seed()
    tr = json.load(open(I18N_PATH, encoding='utf-8'))
    build_strings()
    for lang, page in PAGES.items():
        html = translate(lang, tr)
        open(os.path.join(PUB, page), 'w', encoding='utf-8').write(html)
        print(f'public/{page}: {len(html)//1024} KB')
    print('public/js/t.{uz,ru,en}.js written')
